export function findCurrency(codeOrValue?: string): CurrencyItem | undefined {
  if (!codeOrValue) return undefined;
  const needle = codeOrValue.toUpperCase().trim();
  return (
    CURRENCIES.find((c) => c.code === needle) ||
    CURRENCIES.find((c) => c.value === needle) ||
    CURRENCIES.find((c) => c.name.toLowerCase() === codeOrValue.toLowerCase().trim())
  );
}
