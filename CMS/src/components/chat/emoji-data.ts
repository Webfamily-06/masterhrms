// Flat list for global search
export const ALL_EMOJIS: EmojiItem[] = EMOJI_CATEGORIES.flatMap((c) => c.emojis);

// Search helper
export function searchEmojis(query: string): EmojiItem[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return ALL_EMOJIS;
  return ALL_EMOJIS.filter(
    (item) =>
      item.emoji.includes(clean) ||
      item.name.toLowerCase().includes(clean) ||
      item.keywords.some((k) => k.toLowerCase().includes(clean))
  );
}

