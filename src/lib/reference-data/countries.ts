export function findCountry(codeOrName?: string): CountryItem | undefined {
  if (!codeOrName) return undefined;
  const needle = codeOrName.toLowerCase().trim();
  return (
    COUNTRIES.find((c) => c.code.toLowerCase() === needle) ||
    COUNTRIES.find((c) => c.name.toLowerCase() === needle) ||
    COUNTRIES.find((c) => c.value.toLowerCase() === needle)
  );
}
